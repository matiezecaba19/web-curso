
// estructura repetitiva for
for(let i = 0; i < 10; i++) {
  console.log(`Se pegaron ${i + 1} vueltas`);
  
}


// estructura repetitiva while
let n = 0;
while (n !== 10) {
  console.log("Vueltas");
  
  n ++;
}


// do while entra almenos una vez
let control = 5; // probarlo con 0

do {
    console.log("Entro al do while");
    control ++;
} while (control < 5); // menor a 5


